function build_kinematic_bicycle()
% BUILD_KINEMATIC_BICYCLE Builds adaptive_path_controller.slx
% Exact discrete port of engine/simulation/vehicle.py KinematicBicycleModel

model_name = 'adaptive_path_controller';
mdl_dir = fileparts(mfilename('fullpath'));
mdl_path = fullfile(mdl_dir, [model_name, '.slx']);

if bdIsLoaded(model_name)
    close_system(model_name, 0);
end
if exist(mdl_path, 'file')
    delete(mdl_path);
end

new_system(model_name);
load_system(model_name);

set_param(model_name, 'SolverType', 'Fixed-step');
set_param(model_name, 'Solver', 'FixedStepDiscrete');
set_param(model_name, 'FixedStep', '0.05');
set_param(model_name, 'StopTime', '10.0');
set_param(model_name, 'SaveTime', 'on');
set_param(model_name, 'SaveOutput', 'on');
set_param(model_name, 'TimeSaveName', 'tout');
set_param(model_name, 'OutputSaveName', 'yout');
set_param(model_name, 'SaveFormat', 'Dataset');

block_path = [model_name, '/KinematicBicycleCore'];
add_block('simulink/User-Defined Functions/MATLAB Function', block_path);

func_str = [
'function [x, y, yaw, v, actual_steer, actual_accel] = fcn(accel_cmd, steer_cmd, x0, y0, yaw0, v0, steer0, accel0)' newline ...
'% KINEMATIC BICYCLE MODEL CORE (ISO 8855)' newline ...
'% Exact discrete Forward Euler matching engine/simulation/vehicle.py' newline ...
'persistent px py pyaw pv p_steer p_accel initialized' newline ...
'if isempty(initialized)' newline ...
'    px = x0;' newline ...
'    py = y0;' newline ...
'    pyaw = yaw0;' newline ...
'    pv = v0;' newline ...
'    p_steer = steer0;' newline ...
'    p_accel = accel0;' newline ...
'    initialized = true;' newline ...
'end' newline ...
'' newline ...
'% Parameters' newline ...
'wheelbase = 2.6;' newline ...
'dist_cg_to_rear = 1.3;' newline ...
'max_steer_rad = 0.60;' newline ...
'max_accel_m_s2 = 2.5;' newline ...
'max_decel_m_s2 = -6.5;' newline ...
'max_steer_rate_rad_s = 0.8;' newline ...
'max_jerk_m_s3 = 10.0;' newline ...
'dt = 0.05;' newline ...
'' newline ...
'% 1. Saturation clamping' newline ...
's_sat = max(-max_steer_rad, min(max_steer_rad, steer_cmd));' newline ...
'a_sat = max(max_decel_m_s2, min(max_accel_m_s2, accel_cmd));' newline ...
'' newline ...
'% 2. Rate limiting' newline ...
'd_steer_max = max_steer_rate_rad_s * dt;' newline ...
'actual_steer = max(p_steer - d_steer_max, min(p_steer + d_steer_max, s_sat));' newline ...
'd_accel_max = max_jerk_m_s3 * dt;' newline ...
'actual_accel = max(p_accel - d_accel_max, min(p_accel + d_accel_max, a_sat));' newline ...
'' newline ...
'% 3. Kinematic slip angle at CG' newline ...
'beta = atan((dist_cg_to_rear / wheelbase) * tan(actual_steer));' newline ...
'' newline ...
'% 4. Derivatives' newline ...
'dx = pv * cos(pyaw + beta);' newline ...
'dy = pv * sin(pyaw + beta);' newline ...
'd_yaw = (pv / wheelbase) * cos(beta) * tan(actual_steer);' newline ...
'' newline ...
'% 5. State output at step k' newline ...
'x = px;' newline ...
'y = py;' newline ...
'yaw = pyaw;' newline ...
'v = pv;' newline ...
'' newline ...
'% 6. Forward Euler updates for next step k+1' newline ...
'px = px + dx * dt;' newline ...
'py = py + dy * dt;' newline ...
'pyaw = mod(pyaw + d_yaw * dt, 2 * pi);' newline ...
'pv = max(0.0, pv + actual_accel * dt);' newline ...
'p_steer = actual_steer;' newline ...
'p_accel = actual_accel;' newline ...
];

sf = sfroot;
m = sf.find('Name', 'KinematicBicycleCore', '-isa', 'Stateflow.EMChart');
m.Script = func_str;

% Inports and Constants
add_block('simulink/Sources/In1', [model_name, '/accel_cmd'], 'Position', [40, 40, 70, 54]);
add_block('simulink/Sources/In1', [model_name, '/steer_cmd'], 'Position', [40, 80, 70, 94]);
add_block('simulink/Sources/Constant', [model_name, '/x0'], 'Value', '0.0', 'Position', [40, 120, 70, 134]);
add_block('simulink/Sources/Constant', [model_name, '/y0'], 'Value', '0.0', 'Position', [40, 160, 70, 174]);
add_block('simulink/Sources/Constant', [model_name, '/yaw0'], 'Value', '0.0', 'Position', [40, 200, 70, 214]);
add_block('simulink/Sources/Constant', [model_name, '/v0'], 'Value', '0.0', 'Position', [40, 240, 70, 254]);
add_block('simulink/Sources/Constant', [model_name, '/steer0'], 'Value', '0.0', 'Position', [40, 280, 70, 294]);
add_block('simulink/Sources/Constant', [model_name, '/accel0'], 'Value', '0.0', 'Position', [40, 320, 70, 334]);

% Outports
add_block('simulink/Sinks/Out1', [model_name, '/x'], 'Position', [450, 40, 480, 54]);
add_block('simulink/Sinks/Out1', [model_name, '/y'], 'Position', [450, 80, 480, 94]);
add_block('simulink/Sinks/Out1', [model_name, '/yaw'], 'Position', [450, 120, 480, 134]);
add_block('simulink/Sinks/Out1', [model_name, '/v'], 'Position', [450, 160, 480, 174]);
add_block('simulink/Sinks/Out1', [model_name, '/actual_steer'], 'Position', [450, 200, 480, 214]);
add_block('simulink/Sinks/Out1', [model_name, '/actual_accel'], 'Position', [450, 240, 480, 254]);

% Connect Inports to MATLAB Function
add_line(model_name, 'accel_cmd/1', 'KinematicBicycleCore/1');
add_line(model_name, 'steer_cmd/1', 'KinematicBicycleCore/2');
add_line(model_name, 'x0/1', 'KinematicBicycleCore/3');
add_line(model_name, 'y0/1', 'KinematicBicycleCore/4');
add_line(model_name, 'yaw0/1', 'KinematicBicycleCore/5');
add_line(model_name, 'v0/1', 'KinematicBicycleCore/6');
add_line(model_name, 'steer0/1', 'KinematicBicycleCore/7');
add_line(model_name, 'accel0/1', 'KinematicBicycleCore/8');

% Connect MATLAB Function to Outports
add_line(model_name, 'KinematicBicycleCore/1', 'x/1');
add_line(model_name, 'KinematicBicycleCore/2', 'y/1');
add_line(model_name, 'KinematicBicycleCore/3', 'yaw/1');
add_line(model_name, 'KinematicBicycleCore/4', 'v/1');
add_line(model_name, 'KinematicBicycleCore/5', 'actual_steer/1');
add_line(model_name, 'KinematicBicycleCore/6', 'actual_accel/1');

set_param(block_path, 'Position', [150, 30, 350, 350]);

save_system(model_name, mdl_path);
close_system(model_name);

disp(['Successfully built and saved: ', mdl_path]);
end
